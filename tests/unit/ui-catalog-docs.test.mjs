// The generated component reference (plan G001, rule project.visual-components-framed):
// docs/components.md is exactly what scripts/ui-catalog/docs.mjs renders from the catalogue and
// its trace, so a hand edit or a declaration changed without regenerating fails here.
//
// What it proves:
//   - the committed docs/components.md equals renderComponents(CATALOG, traces);
//   - the rendering is byte-stable and names every visual component with its frame hooks and
//     full-screen controls, and every declaration;
//   - mutation: a hand edit of the Markdown, and a declaration changed in a copy of the
//     catalogue, both make the check fail; `node scripts/ui-catalog/docs.mjs --check` exits 1 on
//     a drifted file.
//   node --test tests/unit/ui-catalog-docs.test.mjs

import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { CATALOG, DECLARATIONS, createCatalog } from '../../src/js/ui/catalog/registry.js';
import { DOC_REL, renderComponents } from '../../scripts/ui-catalog/docs.mjs';
import { loadTraces, ROOT } from '../../scripts/ui-catalog/check.mjs';

const traces = await loadTraces(ROOT);
const committed = readFileSync(path.join(ROOT, DOC_REL), 'utf8');

test('docs/components.md is what the catalogue generates (never edited by hand)', () => {
  assert.equal(committed, renderComponents(CATALOG, traces),
    'run node scripts/ui-catalog/docs.mjs');
});

test('the reference is byte-stable and names every component and every frame', () => {
  const a = renderComponents(CATALOG, traces);
  assert.equal(renderComponents(CATALOG, traces), a);
  for (const d of CATALOG.visuals()) {
    assert.ok(a.includes(`| \`${d.id}\` | ${d.label.replace(/\|/g, '\\|')} | \`${d.id}.fullscreen\``),
      d.id);
    for (const c of d.fullscreenControls || []) assert.ok(a.includes(`\`${c.id}\``), c.id);
  }
  for (const d of CATALOG.list()) assert.ok(a.includes(`\`${d.id}\``), d.id);
  assert.match(a, /Generated by scripts\/ui-catalog\/docs\.mjs/);
});

test('mutation: a hand edit and an undocumented declaration change both drift', () => {
  const edited = committed.replace('| Peeper |', '| Peeper (hand edit) |');
  assert.notEqual(edited, committed);
  assert.notEqual(edited, renderComponents(CATALOG, traces));
  const changed = DECLARATIONS.map((d) => (d.id === 'peeper'
    ? { ...JSON.parse(JSON.stringify(d)), docs: 'Watches a signal in a sentence nobody rendered.' }
    : d));
  assert.notEqual(renderComponents(createCatalog(changed), traces), committed);
});
