#!/usr/bin/env node
// The component reference (plan G001, rule project.visual-components-framed): docs/components.md
// generated from the UI catalogue (src/js/ui/catalog/registry.js) and its trace
// (scripts/ui-catalog/trace). Never edit the Markdown by hand: tests/unit/ui-catalog-docs.test.mjs
// runs the check in `npm test`, and a hand edit fails it.
//
//   node scripts/ui-catalog/docs.mjs           # write docs/components.md
//   node scripts/ui-catalog/docs.mjs --check   # exit 1 when docs/components.md is not what the
//                                              # catalogue generates
//   renderComponents(catalog, traces) -> markdown   (pure, byte-stable)

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATALOG } from '../../src/js/ui/catalog/registry.js';
import { frameHooksOf, hooksOf } from '../../src/js/ui/catalog/define.js';
import { loadTraces, ROOT } from './check.mjs';

export const DOC_REL = 'docs/components.md';

const cell = (v) => String(v ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const code = (v) => (v ? `\`${v}\`` : '');
const stateOf = (d) => (typeof d.state === 'string' ? code(d.state) : `none: ${d.state.none}`);
const byId = (a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0);

/** The reference as Markdown: the visual components and their frames, then every component. */
export function renderComponents(catalog, traces = {}) {
  const decls = catalog.list().filter((d) => d.kind !== 'node-face').slice().sort(byId);
  const visuals = catalog.visuals().slice().sort(byId);
  const faces = catalog.nodeFaces();
  const kinds = new Map();
  for (const d of decls) kinds.set(d.kind, (kinds.get(d.kind) || 0) + 1);
  const out = [
    '# Components',
    '',
    '<!-- Generated by scripts/ui-catalog/docs.mjs from src/js/ui/catalog; do not edit. -->',
    '',
    'Every component of the interface, as the UI catalogue declares it (plan G001, ADR 0081):',
    'its hook, kind, label, the sentence the app shows, the state it reads or writes, and where',
    'its trace says it comes from and is tested. Regenerate with',
    '`node scripts/ui-catalog/docs.mjs`; `npm test` fails when this file and the catalogue differ.',
    '',
    `${decls.length} declarations, ${faces.length} derived node faces, ${visuals.length} visual `
      + 'components. By kind: '
      + [...kinds.entries()].sort().map(([k, n]) => `${k} ${n}`).join(', ') + '.',
    '',
    '## Visual components and the one frame',
    '',
    'Rule `project.visual-components-framed`: each one renders inside the one frame',
    '(`src/js/ui/catalog/frame.js`), which gives it full screen (the Fullscreen API, or a fixed',
    'overlay inside the safe area where an element has none), Escape and Back to leave it, a',
    'size class from its own box (`phone` under 480 px, `small` under 1024 px, `large`), and,',
    'when it declares full-screen controls, a menu (`<hook>.frame`) listing every option.',
    '',
    '| Hook | Label | Frame hooks | Full-screen controls | What it shows |',
    '| --- | --- | --- | --- | --- |',
  ];
  for (const d of visuals) {
    const controls = (d.fullscreenControls || [])
      .map((c) => `${code(c.id)} (${c.kind}, ${cell(c.label)}): ${cell(c.docs)}`).join('; ');
    out.push(`| ${code(d.id)} | ${cell(d.label)} | ${frameHooksOf(d)
      .filter((h) => h === `${d.id}.fullscreen` || h === `${d.id}.frame`).map(code).join(', ')} | ${controls || 'none'} | ${cell(d.docs)} |`);
  }
  out.push('', '## Every component', '',
    '| Hook | Kind | Label | Docs | State | Hooks | Source | Plan | Tests |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const d of decls) {
    const t = traces[d.id] || {};
    const hooks = hooksOf(d).filter((h) => h !== d.id);
    const shown = hooks.length > 6 ? `${hooks.slice(0, 6).map(code).join(', ')} and ${
      hooks.length - 6} more` : hooks.map(code).join(', ');
    const id = d.pattern ? `${code(d.id)} (pattern ${code(d.pattern.template)})` : code(d.id);
    out.push(`| ${id}${d.visual ? ' (visual)' : ''} | ${d.kind} | ${cell(d.label)} | ${
      cell(d.docs)} | ${cell(stateOf(d))} | ${shown} | ${code(t.source)} | ${
      (t.plan || []).join(', ')} | ${(t.tests || []).map((f) => code(f.replace(/^tests\//, '')))
      .join(', ')} |`);
  }
  out.push('', '## Derived node faces', '',
    'One per node type of the Studio node registry, derived and never declared by hand.', '',
    '| Hook | Label | Docs |', '| --- | --- | --- |');
  for (const d of faces) out.push(`| ${code(d.id)} | ${cell(d.label)} | ${cell(d.docs)} |`);
  out.push('');
  return out.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const want = renderComponents(CATALOG, await loadTraces(ROOT));
  const abs = path.join(ROOT, DOC_REL);
  if (process.argv.includes('--check')) {
    let have = null;
    try { have = readFileSync(abs, 'utf8'); } catch (e) { have = null; }
    if (have !== want) {
      console.log(`${DOC_REL} is not what the catalogue generates: run node scripts/ui-catalog/`
        + 'docs.mjs (never edit it by hand)');
      process.exit(1);
    }
    console.log(`${DOC_REL}: current`);
  } else {
    writeFileSync(abs, want);
    console.log(`wrote ${DOC_REL}`);
  }
}
