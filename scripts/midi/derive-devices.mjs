#!/usr/bin/env node
// MIDI device profiles derived from a local Arturia install (plan issue V507; ADR 0058, its
// V507 note; docs/midi-devices.md).
//
// The maker's editor (MIDI Control Center) ships, for each controller it edits, a device
// description (Resources/<device>.json: the controls, their kinds and banks, the identity
// numbers, the memories) and a factory template (Templates/<device>/Factory/Default.*: the
// message each control sends: "<item>_<param>": value, param 1 the mode, 2 the channel, 3 the
// controller or note number). The classic-synth plug-ins ship their default MIDI map
// (<plug-in>/resources/plugin.prefmidi.xml: controller -> paramid, an index into the <vst>
// list of Reference_ParamNames.xml). This script reads those files where they are installed
// and writes only facts derived from them:
//
//   src/data/midi-devices.json   per device: its names, its SysEx identity numbers, how many
//                                memories it has (their names, which can name other
//                                products, stay in the dump), and per control: kind, bank,
//                                message, channel, number. Committed; src/js/midi/devices.js
//                                reads it.
//   docs/midi-devices.md         the generated region between the midi-devices markers: the
//                                device table, and per controller number how many plug-ins
//                                read it and the role most of them give it.
//   --dump <dir>                 the full decode of every file read, for a person to inspect
//                                (default .local/midi, ignored by git; never committed).
//
// Nothing of the maker's is copied: no image, layout file, template, preset, firmware, product
// key or text beyond a parameter's own short name. The images (Resources/*.png), the editor
// layouts (*.ui), the firmware (Firmware/) and every key field (productKey, firmwareUpdater)
// are not even read.
//
//   node scripts/midi/derive-devices.mjs [--root /Library/Arturia] [--check] [--dump <dir>]
//
// --check derives again and fails when the committed profile or the docs region differs (it
// passes, saying so, where the install is absent, as on CI). Exit codes: 0 written or current;
// 1 the committed files differ (--check) or the install could not be read; 2 usage.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..', '..');
export const PROFILE_PATH = join(REPO, 'src', 'data', 'midi-devices.json');
export const DOCS_PATH = join(REPO, 'docs', 'midi-devices.md');
export const DOCS_BEGIN = '<!-- midi-devices:begin (generated by scripts/midi/derive-devices.mjs) -->';
export const DOCS_END = '<!-- midi-devices:end -->';
const EDITOR = 'MIDI Control Center';

/** JSON as the maker's files write it: trailing commas, leading zeros, raw tabs. */
export function parseLenient(text) {
  try { return JSON.parse(text); } catch { /* repaired below */ }
  const fixed = String(text)
    .replace(/\t/g, ' ')
    .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, ' ')
    .replace(/,(\s*[}\]])/g, '$1')
    .replace(/(:\s*-?)0+(\d)/g, '$1$2');
  return JSON.parse(fixed);
}

/** The editor's channel codes: 0-15 a channel (shown 1-16), 65 the user channel, 66-68 parts. */
export const CHANNEL_CODES = Object.freeze({ 65: 'user', 66: 'part1', 67: 'part2', 68: 'both' });
export function channelOf(code) {
  if (Number.isInteger(code) && code >= 0 && code <= 15) return code + 1;
  return CHANNEL_CODES[code] || null;
}

/** The editor's mode codes (param 1) that send a message OSCILLA reads, by message kind. */
export const MODE_MESSAGES = Object.freeze({ 1: 'cc', 8: 'cc-switch', 11: 'note',
  4: 'nrpn', 12: 'program' });

/** A stable id: lower case, words joined by '-'. */
export function slug(s) {
  return String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

/** Two hex digits per byte: '0562' -> [5, 98]. */
export function hexBytes(s) {
  return typeof s === 'string' && /^([0-9a-f]{2})+$/i.test(s)
    ? s.match(/../g).map((h) => parseInt(h, 16)) : null;
}

/**
 * One device's profile from its description `d` and its factory template `t` (both parsed).
 * Controls whose template entry sends nothing OSCILLA reads are left out.
 */
export function deriveDevice(d, t) {
  const controls = [];
  for (const c of d.controls || []) {
    if (!c || !Array.isArray(c.items) || c.displayed_on_test_only) continue;
    c.items.forEach((it, i) => {
      const mode = t[`${it.id}_1`];
      const message = MODE_MESSAGES[mode];
      if (!message) return;
      const number = t[`${it.id}_3`];
      if (!Number.isInteger(number) || number < 0 || number > 127) return;
      const bankName = /^bank\s*(\d+)/i.exec(String(it.name || ''));
      controls.push({ id: String(c.id), kind: String(it.type || 'control'),
        bank: bankName ? Number(bankName[1]) : (c.items.length > 1 ? i + 1 : 1),
        message, channel: channelOf(t[`${it.id}_2`]), number });
    });
  }
  const names = [d.name, ...(d.alternatives || []).map((a) => a && a.altName)]
    .filter((n) => typeof n === 'string' && n.trim());
  const members = (d.alternatives || []).map((a) => a && hexBytes(a.familyMemberId))
    .filter(Boolean);
  return {
    id: slug(d.name),
    name: d.name,
    names: [...new Set(names)],
    identity: { manufacturer: hexBytes(d.manufacturerId), family: hexBytes(d.familyId),
      members },
    memories: Array.isArray(d.memories_name) ? d.memories_name.length : 0,
    controls,
  };
}

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

function readJson(path) {
  const buf = readFileSync(path);
  return { data: parseLenient(buf.toString('utf8')), sha: sha256(buf) };
}

/** Every editable device of the editor under `root`, with its factory template. */
export function readDevices(root) {
  const base = join(root, EDITOR);
  const res = join(base, 'Resources');
  const tdir = join(base, 'Templates');
  const templates = new Map(); // device name -> { data, sha, file }
  for (const dev of readdirSync(tdir)) {
    const fdir = join(tdir, dev, 'Factory');
    if (!existsSync(fdir)) continue;
    for (const f of readdirSync(fdir).sort()) {
      if (!/^Default\./.test(f)) continue;
      try {
        const r = readJson(join(fdir, f));
        if (r.data && r.data.device && !templates.has(r.data.device)) {
          templates.set(r.data.device, { ...r, file: `Templates/${dev}/Factory/${f}` });
        }
      } catch { /* an unreadable template leaves its device out */ }
    }
  }
  const devices = [];
  const skipped = [];
  for (const f of readdirSync(res).sort()) {
    if (!f.endsWith('.json') || /Test\.json$/.test(f)) continue;
    let r;
    try { r = readJson(join(res, f)); } catch (e) { skipped.push(`${f}: ${e.message}`); continue; }
    const d = r.data;
    if (!d || typeof d !== 'object' || !Array.isArray(d.controls) || !d.controls.length) continue;
    const t = templates.get(d.name);
    if (!t) { skipped.push(`${f}: no factory template`); continue; }
    const p = deriveDevice(d, t.data);
    if (!p.controls.length) { skipped.push(`${f}: no control sends a message read here`); continue; }
    p.source = { description: `Resources/${f}`, descriptionSha256: r.sha,
      template: t.file, templateSha256: t.sha };
    devices.push({ profile: p, raw: { description: d, template: t.data } });
  }
  return { devices, skipped };
}

/** The installed editor's version, from its bundle (macOS), or null. */
export function editorVersion(apps = '/Applications/Arturia') {
  const plist = join(apps, `${EDITOR}.app`, 'Contents', 'Info.plist');
  if (!existsSync(plist)) return null;
  const m = /<key>CFBundleShortVersionString<\/key>\s*<string>([^<]+)<\/string>/
    .exec(readFileSync(plist, 'utf8'));
  return m ? m[1] : null;
}

/** The configuration names a map gives its controller-independent layout. */
export const GENERIC_CONFIGS = Object.freeze(['Default', 'Generic']);

/** Every plug-in's generic controller map: [{ plugin, config, cc, name, display }]. */
export function readPluginMaps(root) {
  const rows = [];
  const skipped = [];
  for (const dir of readdirSync(root).sort()) {
    const r = join(root, dir, 'resources');
    const pref = join(r, 'plugin.prefmidi.xml');
    const names = join(r, 'Reference_ParamNames.xml');
    if (!existsSync(pref) || !existsSync(names)) continue;
    const vst = /<vst[^>]*>([\s\S]*?)<\/vst>/.exec(readFileSync(names, 'utf8'));
    if (!vst) { skipped.push(`${dir}: no <vst> parameter list`); continue; }
    const params = [...vst[1].matchAll(/<param\b([^>]*)\/?>/g)].map((m) => attrs(m[1]));
    // A map holds one configuration per controller family ("Default" or "Generic" for any
    // controller, then one per family); the generic one is the layout every controller reads.
    const configs = [...readFileSync(pref, 'utf8')
      .matchAll(/<midiconfig\b([^>]*)>([\s\S]*?)<\/midiconfig>/g)]
      .map((m) => ({ name: attrs(m[1]).name || '', body: m[2] }));
    const cfg = configs.find((c) => GENERIC_CONFIGS.includes(c.name)) || configs[0];
    const assigns = cfg ? [...cfg.body.matchAll(/<assignment\b([^>]*)\/?>/g)]
      .map((m) => attrs(m[1])) : [];
    if (!assigns.length) { skipped.push(`${dir}: no assignment`); continue; }
    for (const a of assigns) {
      const cc = Number(a.controller);
      const p = params[Number(a.paramid)];
      if (!Number.isInteger(cc) || !p) continue;
      rows.push({ plugin: dir, config: cfg.name, cc, name: p.name || '',
        display: p.display_name || p.name || '' });
    }
  }
  return { rows, skipped };
}

function attrs(s) {
  const o = {};
  for (const m of s.matchAll(/([\w:-]+)\s*=\s*"([^"]*)"/g)) o[m[1]] = m[2];
  return o;
}

/** Per controller number: how many plug-ins read it and the role most of them give it. */
export function consensus(rows) {
  const by = new Map();
  for (const r of rows) {
    const role = roleOf(r.display || r.name);
    if (!by.has(r.cc)) by.set(r.cc, { plugins: new Set(), roles: new Map() });
    const e = by.get(r.cc);
    e.plugins.add(r.plugin);
    if (!e.roles.has(role)) e.roles.set(role, new Set());
    e.roles.get(role).add(r.plugin); // a plug-in counts once per role
  }
  return [...by.entries()].sort((a, b) => a[0] - b[0]).map(([cc, e]) => {
    const ranked = [...e.roles.entries()]
      .sort((a, b) => b[1].size - a[1].size || (a[0] < b[0] ? -1 : 1));
    const [role, set] = ranked[0];
    const next = ranked[1] ? `${ranked[1][0]} (${ranked[1][1].size})` : '';
    return { cc, plugins: e.plugins.size, role, agree: set.size, next };
  });
}

/** A parameter's short name reduced to its role: the words that say what it does. */
export function roleOf(display) {
  const s = String(display).toLowerCase();
  const roles = [
    ['macro', /macro|hardwarecontrol/], ['mix', /dry ?\/ ?wet|mix\b/],
    ['resonance', /reso|peak|\bres\b|response|emphasis/],
    ['cutoff', /cutoff|filter freq|lpf cutoff|brilliance/],
    ['lfo rate', /(lfo|mg|vibrato|tremolo)\w* (rate|speed|freq)|rate lfo/],
    ['lfo amount', /(lfo|mg|vibrato|tremolo)\w* (amount|amp|depth)/],
    ['env amount', /(env|eg|contour)\w*.*(amount|mod\b)|envelope mod/],
    ['attack', /attack/], ['decay', /decay/], ['sustain', /sustain/], ['release', /release/],
    ['volume', /volume|main ?level|master/],
  ];
  for (const [role, re] of roles) if (re.test(s)) return role;
  return s.replace(/[^a-z0-9 ]+/g, ' ').trim().split(/\s+/).slice(0, 2).join(' ') || 'other';
}

/** The committed profile file's whole text. */
export function profileText(devices, version) {
  const out = {
    schema: 1,
    derivedBy: 'scripts/midi/derive-devices.mjs',
    editor: { name: EDITOR, version: version || null },
    channels: 'number 1-16, or user (the device-wide user channel), part1, part2, both',
    devices: devices.map((d) => d.profile).sort((a, b) => (a.id < b.id ? -1 : 1)),
  };
  return `${JSON.stringify(out, null, 1)}\n`;
}

/** The generated region of docs/midi-devices.md. */
export function docsRegion(devices, table, version) {
  const lines = [DOCS_BEGIN, '',
    `Derived from ${EDITOR} ${version || '(version unknown)'} and ${new Set(table.plugins).size} plug-in maps.`, '',
    '| Device | Names it reports | Controls read | Kinds |', '|---|---|---|---|'];
  for (const { profile: p } of [...devices].sort((a, b) => (a.profile.id < b.profile.id ? -1 : 1))) {
    const kinds = [...new Set(p.controls.map((c) => c.kind))].sort().join(', ');
    lines.push(`| ${p.name} | ${p.names.join(', ')} | ${p.controls.length} | ${kinds} |`);
  }
  lines.push('', '| CC | Plug-ins reading it | Most common role (plug-ins) | Next role (plug-ins) |',
    '|---|---|---|---|');
  for (const r of table.rows) {
    lines.push(`| ${r.cc} | ${r.plugins} | ${r.role} (${r.agree}) | ${r.next || '-'} |`);
  }
  lines.push('', DOCS_END);
  return lines.join('\n');
}

export function spliceDocs(text, region) {
  const a = text.indexOf(DOCS_BEGIN);
  const b = text.indexOf(DOCS_END);
  if (a < 0 || b < a) throw new Error(`${DOCS_PATH} has no midi-devices markers`);
  return text.slice(0, a) + region + text.slice(b + DOCS_END.length);
}

function main(argv) {
  let root = '/Library/Arturia';
  let check = false;
  let dump = join(REPO, '.local', 'midi');
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    if (a === '--root') root = argv[++i];
    else if (a === '--check') check = true;
    else if (a === '--dump') dump = argv[++i];
    else if (a === '--help' || a === '-h') { console.log(readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\nimport ')[0]); return 0; }
    else { console.error(`unknown argument ${a}`); return 2; }
  }
  if (!root || !dump) { console.error('--root and --dump take a path'); return 2; }
  if (!existsSync(join(root, EDITOR))) {
    const msg = `no ${EDITOR} under ${root}`;
    if (check) { console.log(`${msg}: nothing to compare (the committed profile stands)`); return 0; }
    console.error(msg);
    return 1;
  }
  const { devices, skipped } = readDevices(root);
  const plugins = readPluginMaps(root);
  const version = editorVersion();
  const table = { rows: consensus(plugins.rows), plugins: plugins.rows.map((r) => r.plugin) };
  const profile = profileText(devices, version);
  const docs = spliceDocs(readFileSync(DOCS_PATH, 'utf8'), docsRegion(devices, table, version));
  for (const s of [...skipped, ...plugins.skipped]) console.log(`skipped ${s}`);
  if (check) {
    const bad = [];
    if (!existsSync(PROFILE_PATH) || readFileSync(PROFILE_PATH, 'utf8') !== profile) bad.push(PROFILE_PATH);
    if (readFileSync(DOCS_PATH, 'utf8') !== docs) bad.push(DOCS_PATH);
    for (const b of bad) console.error(`${b} differs from the install; run without --check`);
    return bad.length ? 1 : 0;
  }
  writeFileSync(PROFILE_PATH, profile);
  writeFileSync(DOCS_PATH, docs);
  mkdirSync(dump, { recursive: true });
  for (const d of devices) {
    writeFileSync(join(dump, `${d.profile.id}.json`), `${JSON.stringify(d.raw, null, 1)}\n`);
  }
  writeFileSync(join(dump, 'plugin-cc.json'), `${JSON.stringify(plugins.rows, null, 1)}\n`);
  console.log(`${devices.length} devices -> ${basename(PROFILE_PATH)}; `
    + `${plugins.rows.length} plug-in assignments -> ${basename(DOCS_PATH)}; dump in ${dump}`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
